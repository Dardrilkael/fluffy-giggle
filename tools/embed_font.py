#!/usr/bin/env python3
"""Embeds a binary file as a C++ unsigned-char array TU.

The one generator behind libs/ui/src/text/default_font_*.cpp (see
libs/ui/assets/fonts/README.md): the bundled Inter faces ride in the
binary so r2d::load_default_font() never touches the filesystem.

Usage: embed_font.py <input> --symbol <name> --out <output.cpp>
    [--provenance "<face + license line>"] [--license-file <name>]
"""
import argparse
import os
import sys
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("--symbol", required=True,
                        help="the ARRAY's C++ symbol (default_font.cpp pairs a span with it)")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--provenance", default="Inter v4.1, SIL Open Font License 1.1",
                        help="the face-and-license line the header carries")
    parser.add_argument("--license-file", default="OFL.txt",
                        help="the license file name under assets/fonts")
    args = parser.parse_args()

    data = args.input.read_bytes()
    lines = [
        "// GENERATED by tools/embed_font.py from "
        f"{args.input.name} - do not edit by hand (see",
        "// libs/ui/assets/fonts/README.md for the provenance and the",
        "// regeneration commands). " + args.provenance,
        f"// (libs/ui/assets/fonts/{args.license_file}). {len(data)} bytes.",
        "",
        "#include <cstdint>",
        "#include <cstddef>",
        "#include <span>",
        "",
        "#include \"text/default_font.h\"",
        "",
        "namespace ws::ui::r2d::font {",
        "namespace {",
        "",
        "// The raw face bytes, TU-private (a const array has internal",
        "// linkage anyway); the span accessor below is the only reader.",
        f"const std::uint8_t data[] = {{",
    ]
    # 16 bytes per line keeps the source greppable without exploding
    # the file; the array is zero-initialized past the data (a span
    # carries the exact length).
    row = []
    for i, b in enumerate(data):
        row.append(f"0x{b:02X}")
        if len(row) == 16:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines += [
        "};",
        "",
        f"}}  // namespace",
        "",
        f"std::span<const std::uint8_t> {args.symbol}_ttf() {{",
        f"    return {{data, sizeof data}};",
        "}",
        "",
        "}  // namespace ws::ui::r2d::font",
        "",
    ]
    body = "\n".join(lines)
    # Byte-stable output for the same input: no timestamps.
    if args.out.exists() and args.out.read_text(encoding="utf-8") == body:
        print(f"{args.out}: up to date ({len(data)} bytes)")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(body, encoding="utf-8", newline="\n")
    print(f"{args.out}: wrote {len(data)} bytes as {args.symbol}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
