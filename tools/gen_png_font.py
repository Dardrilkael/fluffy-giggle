#!/usr/bin/env python3
"""Regenerate libs/circsim/src/png_font.cpp - the embedded 16-row bitmap
font for the PNG raster exporter (png.hpp).

Renders DejaVu Sans (Bitstream Vera lineage, free license) at 12 px
through PIL, one glyph per ASCII 32..126, thresholded at >= 128 into a
16-row cell (ascent 12 at this size, so row 12 is the baseline and
rows 12..14 carry descenders - row 15 stays blank). Each glyph is
left-trimmed to its ink; the advance is ink width + 2 px letter gap
(space is fixed at 4 px). Re-run after changing size/metrics; the
assertions here keep the table inside the uint16 row cell.
"""

from PIL import Image, ImageDraw, ImageFont

import sys
from pathlib import Path

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
OUT = Path(__file__).resolve().parent.parent / "libs" / "circsim" / "src" / "png_font.cpp"
SIZE = 12
ROWS = 16          # cell height at scale 1
COLS = 16          # uint16 row bits
ADV_GAP = 2       # px of right padding after each glyph's ink
SPACE_ADV = 4

font = ImageFont.truetype(TTF, SIZE)
ascent, descent = font.getmetrics()
assert 1 <= ascent + descent <= ROWS, (ascent, descent)

glyphs = []  # (advance, rows[16] as int lists)
for code in range(32, 127):
    if code == 32:
        glyphs.append((SPACE_ADV, [0] * ROWS))
        continue
    im = Image.new("L", (48, ROWS + 8), 0)
    ImageDraw.Draw(im).text((8, 0), chr(code), font=font, fill=255)
    bb = im.getbbox()  # (l, t, r, b) of ink
    assert bb, f"no ink for {code:#x}"
    left, top, right, bottom = bb
    assert top >= 0 and bottom <= ROWS, (chr(code), bb)
    width = right - left
    assert 1 <= width <= COLS, (chr(code), width)
    rows = []
    for r in range(ROWS):
        bits = 0
        for c in range(width):
            if im.getpixel((left + c, r)) >= 128:
                bits |= 1 << (COLS - 1 - c)
        rows.append(bits)
    glyphs.append((width + ADV_GAP, rows))

# ASCII-art sanity dump (stderr; the C++ goes to argv[1] or stdout) ------
import sys
for sample in ("Rst 2.2k", "Vf1  PULSE(0 12 1m)", "out n_q2_e 0.999"):
    print(f"--- {sample!r} ---", file=sys.stderr)
    for r in range(ROWS):
        line = ""
        for ch in sample:
            o = ord(ch)
            if not 32 <= o <= 126:
                continue
            rows = glyphs[o - 32][1]
            line += "".join("#" if rows[r] & (1 << (COLS - 1 - c)) else "."
                            for c in range(COLS)) + " "
        print(line, file=sys.stderr)
    print(file=sys.stderr)

# C++ emit --------------------------------------------------------------
out = []
out.append("""// The PNG raster exporter's embedded font (png.hpp) - pure data.
//
// Generated by scripts/gen_png_font.py from DejaVu Sans (the Bitstream
// Vera lineage; the license permits redistribution and embedding) at
// 12 px, thresholded at >= 128: ASCII 32..126, one 16-row cell per
// glyph, uint16 row bits (bit 15 = cell column 0), ink left-trimmed,
// advance = ink width + 2 px (space fixed at 4 px). Row 12 is the
// baseline: rows 0..11 above it, 12..14 the descenders, 15 blank.
// Non-ASCII bytes render nothing and add no advance.

#include "png_font.hpp"

namespace ws::circsim {
namespace {

const PngGlyph kFont[95] = {""")
for code in range(32, 127):
    adv, rows = glyphs[code - 32]
    row_txt = ",".join(f"0x{v:04x}" for v in rows)
    out.append(f"    {{{adv}, {{{row_txt}}}}},  // {code:#04x} {chr(code)!r}")
out.append("};")
out.append("""
}  // namespace

const PngGlyph* png_glyph(unsigned char byte) {
    if (byte < 32u || byte > 126u) {
        return nullptr;
    }
    return &kFont[byte - 32u];
}

}  // namespace ws::circsim""")
if len(sys.argv) > 1:
    Path(sys.argv[1]).write_text("\n".join(out) + "\n")
    print(f"wrote {sys.argv[1]} ({len(out)} lines)", file=sys.stderr)
else:
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}", file=sys.stderr)
